// Writes the interviews the AI interviewer ran as plain text for a clinician to read (docs/ai-interview-samples.md):
// per interview, the reason for the visit, then each question the model wrote with its answer and why it was asked.
// No names, numbers or identifiers: interviews are numbered. Run: node --env-file=.env server/scripts/export-ai-interviews.js [limit]
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const limit = Number(process.argv[2]) || 50;
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });
const { rows } = await pool.query(
  `SELECT e.id, r.question_key, r.answer FROM encounters e JOIN interview_responses r ON r.encounter_id = e.id
    WHERE e.interview_engine = 'ai' AND e.id IN (SELECT encounter_id FROM interview_responses WHERE question_key LIKE 'ai.%' GROUP BY 1 LIMIT $1)
    ORDER BY e.id, r.question_key`, [limit]);
const by = new Map();
for (const r of rows) (by.get(r.id) ?? by.set(r.id, []).get(r.id)).push(r);
const out = ['# Sample AI interviews, for clinician review', '',
  'Generated by `node --env-file=.env server/scripts/export-ai-interviews.js`. Each interview is numbered; there are no names or identifiers.',
  'For each: is each question clinically sensible, in a good order, in simple words, and does it stay a question (no diagnosis, no advice)? Is anything important missing? Record the reviewer and date below.', '',
  '**Review log:** reviewer: ______  date: ______  verdict: ______', ''];
let n = 0;
for (const items of by.values()) {
  out.push(`## Interview ${++n}`, '');
  const reason = items.find((i) => i.question_key === 'cc.reason')?.answer;
  out.push(`**Reason for visit:** ${reason?.value ?? '(not given)'}`, '');
  for (const i of items.filter((x) => x.question_key.startsWith('ai.')).sort((a, b) => Number(a.question_key.slice(3)) - Number(b.question_key.slice(3)))) {
    const q = i.answer.question ?? {};
    out.push(`${i.question_key.slice(3)}. **${q.text?.[0] ?? '?'}** → ${i.answer.skipped ? 'not answered' : JSON.stringify(i.answer.value)}`, `   - Hindi: ${q.text?.[1] ?? ''}`, `   - Marathi: ${q.text?.[2] ?? ''}`, `   - Why asked: ${q.rationale ?? ''}`);
  }
  out.push('');
}
if (!n) out.push('_No AI interviews recorded yet. Run the interview with AI_INTERVIEW_PROVIDER=gemini first._');
writeFileSync(path.join(root, 'docs', 'ai-interview-samples.md'), `${out.join('\n')}\n`);
console.log(`Wrote docs/ai-interview-samples.md (${n} interview(s))`);
await pool.end();
